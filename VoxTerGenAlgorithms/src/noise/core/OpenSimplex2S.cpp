	constexpr double Grad(std::int64_t seed, std::int64_t xsvp, std::int64_t ysvp, double dx, double dy)
	{
		std::int64_t hash = seed ^ xsvp ^ ysvp;
		hash *= hash_multiplier;
		hash ^= hash >> (64 - n_grads_2d_exponent + 1);

		const std::int64_t gi = hash & ((n_grads_2d - 1) << 1);

		return gradients_2d[gi | 0] * dx + gradients_2d[gi | 1] * dy;
	}

	constexpr double Grad(std::int64_t seed, std::int64_t xrvp, std::int64_t yrvp, std::int64_t zrvp, double dx, double dy, double dz)
	{
		std::int64_t hash = (seed ^ xrvp) ^ (yrvp ^ zrvp);
		hash *= hash_multiplier;
		hash ^= hash >> (64 - n_grads_3d_exponent + 2);

		const std::int64_t gi = hash & ((n_grads_3d - 1) << 2);

		return gradients_3d[gi | 0] * dx + gradients_3d[gi | 1] * dy + gradients_3d[gi | 2] * dz;
	}

	constexpr double Grad(std::int64_t seed, std::int64_t xsvp, std::int64_t ysvp, std::int64_t zsvp, std::int64_t wsvp, double dx, double dy, double dz, double dw)
	{
		std::int64_t hash = seed ^ (xsvp ^ ysvp) ^ (zsvp ^ wsvp);
		hash *= hash_multiplier;
		hash ^= hash >> (64 - n_grads_4d_exponent + 2);

		const std::int64_t gi = hash & ((n_grads_4d - 1) << 2);

		return (gradients_4d[gi | 0] * dx + gradients_4d[gi | 1] * dy) + (gradients_4d[gi | 2] * dz + gradients_4d[gi | 3] * dw);
	}
